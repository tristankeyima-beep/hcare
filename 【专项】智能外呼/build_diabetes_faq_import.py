def copy_row_style(ws, source_row: int, target_row: int) -> None:
    for col in range(1, ws.max_column + 1):
        source = ws.cell(source_row, col)
        target = ws.cell(target_row, col)
        if source.has_style:
            target.font = copy(source.font)
            target.fill = copy(source.fill)
            target.border = copy(source.border)
            target.alignment = copy(source.alignment)
            target.number_format = source.number_format
            target.protection = copy(source.protection)
    ws.row_dimensions[target_row].height = ws.row_dimensions[source_row].height


def main() -> None:
    wb = load_workbook(TEMPLATE)
    ws = wb["工作表1"]

    if ws.max_row > 4:
        ws.delete_rows(5, ws.max_row - 4)

    effective_at = "2026-01-01 00:00:00"
    expires_at = "2050-01-01 00:00:00"

    for idx, row in enumerate(FAQ_ROWS, start=4):
        if idx != 4:
            ws.insert_rows(idx)
            copy_row_style(ws, 4, idx)
        row = (row[0], row[1], row[2], effective_at, expires_at, row[5])
        for col, value in enumerate(row, start=1):
            ws.cell(idx, col).value = value

    ws.column_dimensions["A"].width = 34
    ws.column_dimensions["B"].width = 28
    ws.column_dimensions["C"].width = 32
    ws.column_dimensions["D"].width = 20
    ws.column_dimensions["E"].width = 20
    ws.column_dimensions["F"].width = 72

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    wb.save(OUTPUT)
    print(OUTPUT)
    print(f"rows={len(FAQ_ROWS)}")


